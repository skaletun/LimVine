/**
 * @file    Console.h
 * @brief   Кроссплатформенная инициализация консоли для CLI-инструментов.
 *
 * Зачем: все выводимые строки инструментов (lvrun/lvcook/редактор) и тестов
 * написаны в UTF-8 (кириллица в справках и логах). В Linux/macOS консоль по
 * умолчанию работает в UTF-8, а в Windows активная кодовая страница OEM
 * (CP866/CP1251), из-за чего вывод превращается в «кракозябры».
 *
 * lv::core::initConsole() на Windows:
 *   1) переводит ввод/вывод консоли в CP_UTF8 (SetConsoleOutputCP /
 *      SetConsoleCP) — это не требует прав и обратимо при закрытии процесса;
 *   2) если перенаправления нет, дополнительно включает VT-режим ANSI
 *      (ENABLE_VIRTUAL_TERMINAL_PROCESSING) — полезно цветному выводу
 *      редактора/консоли на Windows 10+.
 * На остальных платформах функция ничего не делает.
 *
 * Вызывать один раз в начале main(). Потоки std::cout/std::printf при этом
 * менять не нужно: они и так отдают UTF-8 байтами.
 */
